import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const KATEX_VERSION = '0.16.11';
const MARKDOWN_IT_VERSION = '14.1.0';
const KATEX_BASE = `https://cdn.jsdelivr.net/npm/katex@${KATEX_VERSION}/dist`;
const MARKDOWN_IT_URL = `https://cdn.jsdelivr.net/npm/markdown-it@${MARKDOWN_IT_VERSION}/dist/markdown-it.min.js`;

const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'utils', 'katexBundle.ts');

async function getText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return await res.text();
}
async function getBase64(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return Buffer.from(await res.arrayBuffer()).toString('base64');
}

const scriptSafe = (s) => s.split('</script').join('<\\/script');

async function main() {
  console.log('Fetching JS…');
  const katexJs = scriptSafe(await getText(`${KATEX_BASE}/katex.min.js`));
  const autoRenderJs = scriptSafe(await getText(`${KATEX_BASE}/contrib/auto-render.min.js`));
  const markdownItJs = scriptSafe(await getText(MARKDOWN_IT_URL));

  console.log('Fetching CSS…');
  let css = await getText(`${KATEX_BASE}/katex.min.css`);

  const woff2Files = [...new Set([...css.matchAll(/url\(fonts\/([\w.-]+\.woff2)\)/g)].map((m) => m[1]))];
  console.log(`Embedding ${woff2Files.length} woff2 fonts…`);
  const fontB64 = {};
  for (const file of woff2Files) {
    fontB64[file] = await getBase64(`${KATEX_BASE}/fonts/${file}`);
  }

  css = css.replace(/src:url\(fonts\/([\w.-]+\.woff2)\)[^;}]*/g, (_m, file) => {
    const b64 = fontB64[file];
    if (!b64) throw new Error(`Missing base64 for ${file}`);
    return `src:url(data:font/woff2;base64,${b64}) format("woff2")`;
  });

  const leftover = css.match(/url\(fonts\//g);
  if (leftover) throw new Error(`CSS still references ${leftover.length} font file(s) by path`);

  const banner = `// AUTO-GENERATED by scripts/genKatexBundle.mjs — do not edit by hand.\n`
    + `// KaTeX ${KATEX_VERSION} + markdown-it ${MARKDOWN_IT_VERSION}; ${woff2Files.length} woff2 fonts embedded as base64.\n`
    + `// Regenerate: node scripts/genKatexBundle.mjs\n`
    + `/* eslint-disable */\n`;

  const out = banner
    + `export const KATEX_JS_SRC = ${JSON.stringify(katexJs)};\n\n`
    + `export const KATEX_AUTORENDER_SRC = ${JSON.stringify(autoRenderJs)};\n\n`
    + `export const MARKDOWN_IT_SRC = ${JSON.stringify(markdownItJs)};\n\n`
    + `export const KATEX_CSS_SRC = ${JSON.stringify(css)};\n`;

  writeFileSync(outPath, out);
  console.log(`Wrote ${outPath}`);
  console.log(`  katex.min.js       ${(katexJs.length / 1024).toFixed(1)} KB`);
  console.log(`  auto-render.min.js ${(autoRenderJs.length / 1024).toFixed(1)} KB`);
  console.log(`  markdown-it.min.js ${(markdownItJs.length / 1024).toFixed(1)} KB`);
  console.log(`  katex.min.css+fonts ${(css.length / 1024).toFixed(1)} KB`);
  console.log(`  total .ts          ${(out.length / 1024).toFixed(1)} KB`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
